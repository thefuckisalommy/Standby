#!/usr/bin/env bash
# A copy of the app folder whose two entry scripts are replaced by their
# single-script bundles (tools/bundle.js), for running the test suites
# against the bundle: STANDBY_TEST_APP_DIR=<copy> python3 test/verify099.py
# The copy keeps lib/ (some tests read the sources), but the bundles
# never load the app's files from disk, so a file missing from a bundle
# fails instead of being picked up. Default copy: standby-bundled/ at the
# repository root.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$ROOT/standby-bundled}"
rm -rf "$DEST"
cp -r "$ROOT/standby" "$DEST"
node "$ROOT/tools/bundle.js" server.js "$DEST/server.js"
node "$ROOT/tools/bundle.js" checkin-receiver/server.js "$DEST/checkin-receiver/server.js"
grep -q 'Generated by tools/bundle.js' "$DEST/server.js"
grep -q 'Generated by tools/bundle.js' "$DEST/checkin-receiver/server.js"
echo "bundled app: $DEST"
